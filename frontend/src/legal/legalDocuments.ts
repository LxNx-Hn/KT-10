export function getLegalDocument(
  id: LegalDocument['id'],
): LegalDocument {
  return id === 'terms' ? TERMS_DOCUMENT : PRIVACY_DOCUMENT;
}

export function hasOperatorMetadata(
  metadata: LegalOperatorMetadata = LEGAL_METADATA,
): boolean {
  return Object.values(metadata).some(
    (value) => typeof value === 'string' && value.trim().length > 0,
  );
}
